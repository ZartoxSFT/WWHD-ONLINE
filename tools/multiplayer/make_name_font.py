#!/usr/bin/env python3
"""Builds the name-tag font of the multiplayer-connection guest mod.

Input: tools/multiplayer/fonts/Cinzel[wght].ttf (SIL Open Font License 1.1, fonts/OFL.txt,
https://github.com/google/fonts/tree/main/ofl/cinzel). Output, in the mod package:
  assets/name_fill.png     white glyphs (alpha = coverage), tinted by the HUD
  assets/name_outline.png  the same glyphs dilated, same layout (drawn dark behind the fill)
  assets/OFL.txt           the font license (the atlases are derived from the font)
  name_font.h              glyph table: atlas rectangle, offset from the pen on the baseline, advance

Printable ASCII only (32..126), as the mod accepts in a player name. Needs Pillow.
"""
from pathlib import Path
import shutil

from PIL import Image, ImageDraw, ImageFilter, ImageFont

ROOT = Path(__file__).resolve().parent
FONT = ROOT / "fonts" / "Cinzel[wght].ttf"
PACKAGE = ROOT.parent.parent / "examples" / "guest-mods" / "multiplayer-connection"
SIZE = 40          # pixel size the atlas is rendered at
WEIGHT = 800       # Cinzel's weight axis: 400..900
PAD = 4            # room for the outline around every glyph
OUTLINE = 3        # outline radius in pixels
ATLAS_W = 512


def main():
    font = ImageFont.truetype(str(FONT), SIZE)
    font.set_variation_by_axes([WEIGHT])
    glyphs = []
    for code in range(32, 127):
        ch = chr(code)
        l, t, r, b = font.getbbox(ch, anchor="ls")
        if r <= l or b <= t:
            l, t, r, b = 0, 0, 0, 0
        glyphs.append({"ch": ch, "l": l, "t": t, "w": r - l + 2 * PAD, "h": b - t + 2 * PAD,
                       "adv": font.getlength(ch)})

    x = y = row = 0
    for g in glyphs:
        if x + g["w"] > ATLAS_W:
            x, y, row = 0, y + row, 0
        g["x"], g["y"] = x, y
        x += g["w"]
        row = max(row, g["h"])
    height = 1
    while height < y + row:
        height *= 2

    fill = Image.new("L", (ATLAS_W, height), 0)
    draw = ImageDraw.Draw(fill)
    for g in glyphs:
        if g["w"] > 2 * PAD:
            draw.text((g["x"] + PAD - g["l"], g["y"] + PAD - g["t"]), g["ch"], font=font, fill=255, anchor="ls")
    outline = fill.filter(ImageFilter.MaxFilter(2 * OUTLINE + 1)).filter(ImageFilter.GaussianBlur(0.8))

    def rgba(alpha):
        image = Image.new("RGBA", alpha.size, (255, 255, 255, 0))
        image.putalpha(alpha)
        return image

    assets = PACKAGE / "assets"
    assets.mkdir(exist_ok=True)
    rgba(fill).save(assets / "name_fill.png", optimize=True)
    rgba(outline).save(assets / "name_outline.png", optimize=True)
    shutil.copyfile(ROOT / "fonts" / "OFL.txt", assets / "OFL.txt")

    top = min(g["t"] - PAD for g in glyphs if g["w"] > 2 * PAD)
    bottom = max(g["t"] - PAD + g["h"] for g in glyphs if g["w"] > 2 * PAD)
    cap = -font.getbbox("H", anchor="ls")[1]
    lines = [
        "/* Generated by tools/multiplayer/make_name_font.py from Cinzel (SIL Open Font License 1.1,",
        " * assets/OFL.txt): do not edit. Glyphs of printable ASCII 32..126 in assets/name_fill.png and",
        " * assets/name_outline.png (same layout). Offsets are from the pen position on the baseline. */",
        "#pragma once",
        f"#define NAME_FONT_ATLAS_W {ATLAS_W}",
        f"#define NAME_FONT_ATLAS_H {height}",
        f"#define NAME_FONT_SIZE {SIZE}",
        f"#define NAME_FONT_CAP {cap}      /* cap height above the baseline */",
        f"#define NAME_FONT_TOP ({top})    /* highest glyph cell top, from the baseline */",
        f"#define NAME_FONT_BOTTOM {bottom} /* lowest glyph cell bottom, from the baseline */",
        "#define NAME_FONT_FIRST 32",
        f"#define NAME_FONT_COUNT {len(glyphs)}",
        "typedef struct name_glyph {",
        "    unsigned short x, y, w, h; /* atlas cell (outline padding included) */",
        "    short dx, dy;              /* cell top-left from the pen on the baseline */",
        "    float advance;",
        "} name_glyph;",
        "static const name_glyph name_font[NAME_FONT_COUNT] = {",
    ]
    for g in glyphs:
        lines.append(f"    {{{g['x']}, {g['y']}, {g['w']}, {g['h']}, {g['l'] - PAD}, {g['t'] - PAD}, "
                     f"{g['adv']:.2f}f}}, /* {g['ch']!r} */")
    lines.append("};")
    (PACKAGE / "name_font.h").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"atlas {ATLAS_W}x{height}, {len(glyphs)} glyphs, cap {cap}px")


if __name__ == "__main__":
    main()
